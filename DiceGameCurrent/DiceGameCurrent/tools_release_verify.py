"""The things that are fine in development and fatal on upload.

Why this exists
---------------
Every other check here is about the app being right. This one is about the
app being *shippable*, which is a different and much less forgiving test:
Apple's validator runs after a ten-minute archive, says one line, and
rejects the build. Four of the ways it does that are invisible from
inside the code.

  * **A placeholder bundle identifier.** `com.example.hotdice` is not
    yours, cannot be registered, and is the default this project was
    scaffolded with. Worse than a rejection, it is a trap: an identifier
    is effectively permanent once a build exists under it, so an upload
    that somehow succeeded under the wrong one costs an app record.

  * **No app icon.** `ASSETCATALOG_COMPILER_APPICON_NAME` was set to
    `AppIcon` for weeks with no asset catalog in the project to name. That
    is not a build error. It builds, it archives, and it fails validation.

  * **A launch screen the plist does not point at.** The storyboard lives
    outside the app folder because Swift Playgrounds refuses Interface
    Builder documents, which makes it exactly the kind of file that can
    stop being referenced without anything noticing.

  * **An unanswered export-compliance question**, which does not fail the
    build but does stop the build reaching testers until somebody answers
    a web form, every single time.

**This check is expected to FAIL on a fresh clone**, on the first item,
and that is the point: the sweep should say "set your bundle identifier"
rather than let CI discover it. Everything else here should be green.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.join(HERE, "project.yml")
XCODE_ONLY = os.path.normpath(os.path.join(HERE, "..", "..", "XcodeOnly"))

# Reverse-domain prefixes nobody owns. Apple's own sample code uses the
# first two, which is exactly why they end up shipped.
PLACEHOLDER_PREFIXES = ("com.example", "com.yourcompany", "com.mycompany",
                        "com.test", "org.example")


def read(path):
    with open(path) as handle:
        return handle.read()


def check_bundle_id(problems):
    """Both places the identifier is written, and they must agree."""
    text = read(PROJECT)
    prefix = re.search(r'^\s*bundleIdPrefix:\s*(\S+)', text, re.M)
    product = re.search(r'^\s*PRODUCT_BUNDLE_IDENTIFIER:\s*(\S+)', text, re.M)
    if not prefix or not product:
        problems.append("project.yml no longer states both bundleIdPrefix "
                        "and PRODUCT_BUNDLE_IDENTIFIER — one of them is "
                        "what Apple reads, and which one depends on the "
                        "target, so both are stated on purpose")
        return
    ids = {"bundleIdPrefix": prefix.group(1),
           "PRODUCT_BUNDLE_IDENTIFIER": product.group(1)}
    for key, value in sorted(ids.items()):
        if value.startswith(PLACEHOLDER_PREFIXES):
            problems.append(
                "%s is still %s — a placeholder nobody owns. Set it to an "
                "identifier registered to your team (conventionally your "
                "domain backwards, e.g. com.yourname.hotdice) in BOTH "
                "places in project.yml, and register the same string in "
                "App Store Connect before the first upload"
                % (key, value))
    if not ids["PRODUCT_BUNDLE_IDENTIFIER"].startswith(
            ids["bundleIdPrefix"].rsplit(".", 1)[0]):
        problems.append(
            "PRODUCT_BUNDLE_IDENTIFIER (%s) and bundleIdPrefix (%s) have "
            "drifted apart — a target whose identifier is not under the "
            "project's prefix is the shape that gets one of two bundle "
            "ids registered and not the other"
            % (ids["PRODUCT_BUNDLE_IDENTIFIER"], ids["bundleIdPrefix"]))
    print("  %-26s %s" % ("bundle identifier",
                          ids["PRODUCT_BUNDLE_IDENTIFIER"]))


def check_app_icon(problems):
    """The catalog exists, the project includes it, and it names its file.

    Deliberately NOT a check that the PNG is present: it is generated by
    `tools_icon_export.py` and git-ignored, so in a fresh clone it is
    correctly absent. What must hold is that the catalog asks for exactly
    the filename that exporter produces — a mismatch there is the silent
    version of having no icon at all.
    """
    catalog = os.path.join(XCODE_ONLY, "Assets.xcassets")
    appicon = os.path.join(catalog, "AppIcon.appiconset", "Contents.json")
    if not os.path.exists(appicon):
        problems.append("there is no AppIcon.appiconset in %s, and "
                        "ASSETCATALOG_COMPILER_APPICON_NAME names one — "
                        "the archive will fail App Store validation for "
                        "having no icon" % catalog)
        return

    project = read(PROJECT)
    if "XcodeOnly/Assets.xcassets" not in project:
        problems.append("project.yml does not include "
                        "XcodeOnly/Assets.xcassets, so the catalog exists "
                        "and is not in the build")

    try:
        contents = json.loads(read(appicon))
    except ValueError as error:
        problems.append("AppIcon.appiconset/Contents.json is not valid "
                        "JSON (%s)" % error)
        return

    filenames = [image.get("filename") for image in contents.get("images", [])
                 if image.get("filename")]
    if not filenames:
        problems.append("AppIcon.appiconset names no file — an empty slot "
                        "is the same as no icon to the validator")
        return

    # The exporter's own name for the 1024, read from it rather than typed.
    exporter = read(os.path.join(HERE, "tools_icon_export.py"))
    named = re.search(r'APP_ICON = \("([^"]+)"', exporter)
    expected = (named.group(1) + ".png") if named else None
    if expected and expected not in filenames:
        problems.append(
            "AppIcon.appiconset asks for %s but tools_icon_export.py "
            "writes %s — the catalog would be empty at build time and the "
            "mismatch produces no error, just a missing icon"
            % (", ".join(filenames), expected))
    print("  %-26s %s (generated, git-ignored)"
          % ("app icon", ", ".join(filenames)))


def check_launch_screen(problems):
    """The storyboard is in the build and the plist key points at it."""
    project = read(PROJECT)
    storyboard = os.path.join(XCODE_ONLY, "LaunchScreen.storyboard")
    if not os.path.exists(storyboard):
        problems.append("XcodeOnly/LaunchScreen.storyboard is gone")
        return
    if "XcodeOnly/LaunchScreen.storyboard" not in project:
        problems.append("project.yml does not include the launch "
                        "storyboard, so the app launches on a black screen")
    key = re.search(r'INFOPLIST_KEY_UILaunchStoryboardName:\s*(\S+)', project)
    if not key:
        problems.append("INFOPLIST_KEY_UILaunchStoryboardName is not set, "
                        "so the storyboard is in the bundle and nothing "
                        "loads it")
    elif key.group(1) != "LaunchScreen":
        problems.append("INFOPLIST_KEY_UILaunchStoryboardName is %r but the "
                        "file is LaunchScreen.storyboard" % key.group(1))
    else:
        print("  %-26s LaunchScreen.storyboard, referenced" % "launch screen")


def check_plist_keys(problems):
    """The settings that only exist here, because nothing else carries them."""
    project = read(PROJECT)
    if "GENERATE_INFOPLIST_FILE: YES" not in project:
        problems.append("GENERATE_INFOPLIST_FILE is off, which makes every "
                        "INFOPLIST_KEY_* below it silently do nothing — "
                        "including the orientation pair")
    for key, why in (
            ("INFOPLIST_KEY_UISupportedInterfaceOrientations",
             "portrait-only does not travel in the repo any other way"),
            ("INFOPLIST_KEY_ITSAppUsesNonExemptEncryption",
             "without it, export compliance is a web form to answer after "
             "every single upload")):
        if key not in project:
            problems.append("%s is not set — %s" % (key, why))
    # The pair Apple refuses, caught here rather than at the upload.
    #
    # An iPad app that does not require full screen has its window sized
    # by the system, so Apple will not also let it claim one orientation:
    #
    #     The "UIInterfaceOrientationPortrait" orientations were provided
    #     ... but you need to include all of the ... orientations to
    #     support iPad multitasking
    #
    # That arrived at the END of a twenty-minute job, from Apple's own
    # validator, on a build that had already compiled, signed and
    # uploaded. It is two lines of this file to know it in two seconds.
    ipad = re.search(r'INFOPLIST_KEY_UISupportedInterfaceOrientations_iPad:'
                     r'\s*(.+)', project)
    fullscreen = re.search(r'INFOPLIST_KEY_UIRequiresFullScreen:\s*(\w+)',
                           project)
    if ipad and fullscreen and fullscreen.group(1).upper() == "NO":
        listed = ipad.group(1).split()
        wanted = ["UIInterfaceOrientationPortrait",
                  "UIInterfaceOrientationPortraitUpsideDown",
                  "UIInterfaceOrientationLandscapeLeft",
                  "UIInterfaceOrientationLandscapeRight"]
        missing = [w for w in wanted if w not in listed]
        if missing:
            problems.append(
                "the iPad allows multitasking (UIRequiresFullScreen NO) but "
                "lists only %d of the four orientations — Apple refuses that "
                "pair at upload. Missing: %s"
                % (len(listed), ", ".join(m.replace("UIInterfaceOrientation", "")
                                          for m in missing)))

    print("  %-26s generated plist, iPhone portrait, iPad all four, export "
          "compliance answered" % "plist keys")


def main():
    print("release readiness:")
    problems = []
    check_bundle_id(problems)
    check_app_icon(problems)
    check_launch_screen(problems)
    check_plist_keys(problems)

    if problems:
        print()
        for line in problems:
            print("  FAIL  %s" % line)
        print("\nrelease: FAIL (%d) — not shippable yet" % len(problems))
        return 1
    print("release: PASS (nothing here will be refused on upload)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
